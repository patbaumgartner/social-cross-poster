-- V10: private workspace media library + per-revision media links (UC-13 first
-- slice, ADR-004, ADR-008, ADR-013, ADR-016). Sources stay private to the
-- workspace (authenticated download only, ADR-008) — there is deliberately no
-- public hosting and no platform upload yet; publishing a revision with media is
-- blocked fail-closed until the later UC-13 slice. Alt text is mandatory and
-- local (ADR-016). Content-addressed dedup per workspace via sha256. Dialect
-- kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE media_asset (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    filename     VARCHAR(255) NOT NULL,                   -- original client filename
    content_type VARCHAR(100) NOT NULL,                   -- allow-listed image type only
    size_bytes   BIGINT NOT NULL,
    sha256       CHAR(64) NOT NULL,                       -- content hash, dedup per workspace
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT media_asset_workspace_sha_unique UNIQUE (workspace_id, sha256)
);

-- Media attached to one revision, in order, each with a meaningful local alt
-- text (ADR-016). Links are written when a revision is created (copied from the
-- superseded revision) and can be amended only on the current revision.
CREATE TABLE revision_media (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    revision_id  BIGINT NOT NULL REFERENCES post_revision (id),
    media_id     BIGINT NOT NULL REFERENCES media_asset (id),
    position     INTEGER NOT NULL,                        -- 1-based order within the revision
    alt_text     VARCHAR(1000) NOT NULL,                  -- meaningful local alt text (ADR-016)
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT revision_media_unique UNIQUE (revision_id, media_id)
);

CREATE INDEX media_asset_workspace_idx ON media_asset (workspace_id);
CREATE INDEX revision_media_revision_idx ON revision_media (revision_id);
CREATE INDEX revision_media_media_idx ON revision_media (media_id);
