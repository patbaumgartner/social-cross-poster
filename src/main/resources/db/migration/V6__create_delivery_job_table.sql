-- V6: durable delivery jobs (UC-07 first slice, ADR-015). One job per delivery;
-- the worker claims due jobs with a short lease, executes a bounded retry of the
-- exact frozen payload with backoff, and reconciles UNKNOWN outcomes through the
-- platform reconciler. Dialect kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE delivery_job (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    delivery_id  BIGINT NOT NULL UNIQUE REFERENCES delivery (id),
    state        VARCHAR(24)  NOT NULL DEFAULT 'PENDING',  -- PENDING|RUNNING|SUCCEEDED|EXHAUSTED|CANCELED
    next_run_at  TIMESTAMP WITH TIME ZONE NOT NULL,         -- bounded backoff schedule (UC-07 step 4)
    lease_owner  VARCHAR(64),                               -- worker instance holding the lease
    lease_until  TIMESTAMP WITH TIME ZONE,                  -- expired leases are reclaimed
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX delivery_job_due_idx ON delivery_job (state, next_run_at);
