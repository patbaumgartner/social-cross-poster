-- V2: workspace-scoped connections (provider authorizations) and account
-- destinations (selectable profile/page/chat) per UC-02, ADR-006, ADR-007,
-- ADR-013. Secrets are stored only as AES-GCM ciphertext + nonce + versioned
-- key ID (ADR-007); the key itself lives outside the database (environment).
-- Dialect kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE connection (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id       BIGINT NOT NULL REFERENCES workspace (id),
    platform           VARCHAR(32)  NOT NULL,
    mode               VARCHAR(16)  NOT NULL,             -- pasted | oauth
    provider_principal VARCHAR(255) NOT NULL,            -- e.g. @bot username or DID
    label              VARCHAR(120),
    secret_cipher      TEXT NOT NULL,
    secret_nonce       VARCHAR(64) NOT NULL,
    secret_key_id      VARCHAR(32) NOT NULL,
    health_state       VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',  -- OK | ERROR | UNKNOWN
    last_health_at     TIMESTAMP WITH TIME ZONE,
    enabled            BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Same provider principal can only be connected once per workspace; a
    -- changed principal must become a new connection (ADR-006).
    CONSTRAINT connection_workspace_platform_principal_unique UNIQUE (workspace_id, platform, provider_principal)
);

CREATE TABLE account (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id       BIGINT NOT NULL REFERENCES workspace (id),
    connection_id      BIGINT NOT NULL REFERENCES connection (id),
    platform           VARCHAR(32)  NOT NULL,
    kind               VARCHAR(32)  NOT NULL,             -- channel | group | page | profile
    provider_account_id VARCHAR(255) NOT NULL,           -- chat id, page id, handle
    host               VARCHAR(255),                      -- instance host (Mastodon)
    label              VARCHAR(120) NOT NULL,
    enabled            BOOLEAN NOT NULL DEFAULT TRUE,
    archived           BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Platform alone is never a uniqueness key: the exact destination
    -- (platform + provider account id) is unique within one workspace (UC-02).
    CONSTRAINT account_workspace_platform_provider_unique UNIQUE (workspace_id, platform, provider_account_id)
);

CREATE INDEX connection_workspace_idx ON connection (workspace_id);
CREATE INDEX account_workspace_idx ON account (workspace_id);
CREATE INDEX account_connection_idx ON account (connection_id);
