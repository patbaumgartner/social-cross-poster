-- V11: media snapshot on deliveries (UC-13 second slice, ADR-004, ADR-008,
-- ADR-013, ADR-015). Each delivery snapshots the approved attached images at
-- publication time (content hash of the private media_asset + the local alt text
-- per ADR-016); the dispatch path resolves the private source bytes by hash and
-- fails closed when a source is gone (ADR-008: private originals are retained on
-- local disk, never exposed as public URLs). Dialect kept compatible with H2 in
-- PostgreSQL mode (tests).
CREATE TABLE delivery_media (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    delivery_id  BIGINT NOT NULL REFERENCES delivery (id),
    position     INTEGER NOT NULL,                        -- 1-based order as approved
    sha256       CHAR(64) NOT NULL,                        -- content hash of the media_asset
    alt_text     VARCHAR(1000) NOT NULL,                   -- local alt text snapshot (ADR-016)
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT delivery_media_unique UNIQUE (delivery_id, position)
);

CREATE INDEX delivery_media_delivery_idx ON delivery_media (delivery_id);
