-- V8: one-time publication schedules (UC-10 first slice, ADR-004, ADR-009,
-- ADR-013, ADR-016). One row per approved schedule: the revision and the semantic
-- payload hash are frozen at approval, the local time + IANA timezone + resolved
-- UTC instant are persisted, and dispatch is bounded to scheduled instant + 15
-- minutes (ADR-016). At most one publication per schedule is enforced by the
-- conditional state claim (PENDING -> CREATED). Dialect kept compatible with H2
-- in PostgreSQL mode (tests).
CREATE TABLE publication_schedule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    BIGINT NOT NULL REFERENCES workspace (id),
    post_id         BIGINT NOT NULL REFERENCES post (id),
    revision_id     BIGINT NOT NULL REFERENCES post_revision (id),
    submission_key  VARCHAR(128) NOT NULL,              -- workspace-scoped idempotency key for the created publication (ADR-015)
    payload_hash    VARCHAR(64)  NOT NULL,               -- SHA-256 over the approved payloads, recomputed at dispatch (UC-10 step 5)
    local_date_time TIMESTAMP NOT NULL,                  -- wall-clock time as approved by the owner
    timezone        VARCHAR(64)  NOT NULL,               -- IANA zone id chosen at approval
    scheduled_at    TIMESTAMP WITH TIME ZONE NOT NULL,   -- resolved UTC instant
    state           VARCHAR(24)  NOT NULL DEFAULT 'PENDING',  -- PENDING|CREATED|CANCELED|EXPIRED|NEEDS_REVIEW
    publication_id  BIGINT REFERENCES publication (id), -- set when the schedule created its publication
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT publication_schedule_workspace_key_unique UNIQUE (workspace_id, submission_key)
);
