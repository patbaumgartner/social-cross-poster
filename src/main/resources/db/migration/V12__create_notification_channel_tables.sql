-- V12: external webhook notification channels (UC-12 second slice, ADR-004,
-- ADR-007, ADR-013, ADR-015; SSRF rules per arc42 section 8). Per workspace, an
-- owner configures labeled webhook channels. The URL is validated at save time
-- and re-validated (DNS re-resolved) at send time by OutboundWebhookGuard: https
-- required unless the deployment operator allow-list app.notify.allowed-internal-hosts
-- explicitly permits the host; userinfo, private/loopback/link-local/any-local/
-- multicast/CGNAT ranges, localhost and cloud metadata endpoints are denied.
-- The HMAC signing secret is generated server-side, sealed with the ADR-007
-- cipher bound to AAD "<slug>:notify-webhook:<label>" and never stored or shown
-- in plaintext. categories is a csv of event categories, empty = all.
-- notification_delivery is the deduplicated outbox per (event, channel) with
-- bounded retries (UC-12 step 4); delivery failures never create new events, so
-- notification delivery cannot recurse (UC-12 alternative flow 3). last_detail
-- is redacted: status class or guard reason only, never a response body.
-- Dialect kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE notification_channel (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  BIGINT NOT NULL REFERENCES workspace (id),
    label         VARCHAR(80) NOT NULL,                  -- workspace-unique human label
    url           VARCHAR(2048) NOT NULL,                -- SSRF-validated at save and at send
    secret_cipher VARCHAR(4096) NOT NULL,                -- sealed HMAC secret (base64 GCM), ADR-007
    secret_nonce  VARCHAR(64) NOT NULL,
    secret_key_id VARCHAR(40) NOT NULL,
    categories    VARCHAR(500) NOT NULL DEFAULT '',       -- csv of categories, empty = all
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notification_channel_workspace_label_unique UNIQUE (workspace_id, label)
);

CREATE TABLE notification_delivery (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    BIGINT NOT NULL REFERENCES workspace (id),
    event_id        BIGINT NOT NULL REFERENCES notification_event (id),
    channel_id      BIGINT NOT NULL REFERENCES notification_channel (id),
    state           VARCHAR(16) NOT NULL,                 -- PENDING|SENT|FAILED
    attempts        INTEGER NOT NULL DEFAULT 0,           -- total delivery attempts so far
    last_detail     VARCHAR(500),                         -- redacted: status class / guard reason, never a body
    next_attempt_at TIMESTAMP WITH TIME ZONE,             -- NULL once terminal (SENT/FAILED)
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notification_delivery_event_channel_unique UNIQUE (event_id, channel_id)
);

CREATE INDEX notification_delivery_due_idx ON notification_delivery (state, next_attempt_at);
CREATE INDEX notification_delivery_channel_idx ON notification_delivery (channel_id);
