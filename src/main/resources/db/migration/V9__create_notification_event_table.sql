-- V9: in-app notification events (UC-12 first slice, ADR-004, ADR-013, ADR-015).
-- One durable, deduplicated, redacted event per (workspace, event_key); in-app events
-- are authoritative (UC-12 step 5) while external webhook/SMTP delivery is a later
-- slice. Summaries never contain draft text, images, tokens, raw provider bodies or
-- signed URLs (UC-12 alternative flow 4). Dialect kept compatible with H2 in
-- PostgreSQL mode (tests).
CREATE TABLE notification_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   BIGINT NOT NULL REFERENCES workspace (id),
    event_key      VARCHAR(160) NOT NULL,                -- dedup key, workspace-scoped (UC-12 step 2)
    category       VARCHAR(40) NOT NULL,                 -- DELIVERY_FAILED|DELIVERY_UNKNOWN|RETRIES_EXHAUSTED|DELIVERY_NEEDS_ATTENTION|SCHEDULE_EXPIRED|SCHEDULE_NEEDS_REVIEW
    publication_id BIGINT REFERENCES publication (id),    -- nullable link for the dashboard detail link
    delivery_id    BIGINT REFERENCES delivery (id),
    schedule_id    BIGINT REFERENCES publication_schedule (id),
    summary        VARCHAR(500) NOT NULL,                -- redacted human-readable summary
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notification_event_workspace_key_unique UNIQUE (workspace_id, event_key)
);
