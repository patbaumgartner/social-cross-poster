-- V15: short-lived revocable media import grants (UC-13 fourth slice, main flow
-- steps 3 and 5, ADR-008). For platforms without a verified direct binary upload,
-- dispatch mints one grant per approved attached image: a signed, expiring,
-- revocable /media/grants/{id}?exp=…&sig=… URL bound to workspace, delivery,
-- sha256, purpose, expiry and signing key id. Only the SHA-256 hash of the
-- signature is stored — never the signed URL or any bearer credential (ADR-007
-- redaction). Grants are minted near actual dispatch and revoked once the provider
-- confirmed the import, or when superseded by a retry of the same approved bytes.
-- Dialect kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE media_import_grant (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    delivery_id  BIGINT NOT NULL REFERENCES delivery (id),
    sha256       CHAR(64) NOT NULL,                        -- the exact approved derivative
    purpose      VARCHAR(32) NOT NULL,                     -- e.g. 'platform-import'
    key_id       VARCHAR(32) NOT NULL,                     -- signing key version (ADR-007)
    token_hash   CHAR(64) NOT NULL,                         -- sha256 of the URL signature; not unique: a retry within the same second re-mints the identical signature, and the superseded grant is revoked first
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_media_import_grant_delivery ON media_import_grant (delivery_id);
