-- V3: workspace-scoped contacts and their platform handles per UC-03, ADR-003
-- (point 5: neutral local mention tokens referencing local contacts), ADR-013.
-- The token is the neutral identifier stored in draft text; raw handles stay
-- distinct from resolved/verified native identities. Dialect kept compatible
-- with H2 in PostgreSQL mode (tests).
CREATE TABLE contact (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  BIGINT NOT NULL REFERENCES workspace (id),
    token         VARCHAR(72)  NOT NULL,             -- neutral token {{contact:<uuid>}}, unique app-wide
    display_name  VARCHAR(120) NOT NULL,
    photo         TEXT,                             -- optional data: URI only; no external fetch (ADR-008)
    notes         TEXT,                             -- private: never sent to providers or AI by default (UC-03)
    archived      BOOLEAN NOT NULL DEFAULT FALSE,   -- soft delete; old snapshots keep resolving the token
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT contact_token_unique UNIQUE (token)
);

CREATE TABLE contact_handle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   BIGINT NOT NULL REFERENCES workspace (id),
    contact_id     BIGINT NOT NULL REFERENCES contact (id),
    platform       VARCHAR(32)  NOT NULL,            -- key from the integration catalog (docs/platforms)
    handle         VARCHAR(255) NOT NULL,            -- raw handle as typed, kept distinct from identity_value
    host           VARCHAR(255) NOT NULL DEFAULT '',  -- instance host (Mastodon); '' = none
    identity_kind  VARCHAR(16)  NOT NULL DEFAULT 'none',  -- none | handle | did | urn | url
    identity_value VARCHAR(512),                     -- resolved native identity (DID, URN, ...), if any
    verified       BOOLEAN NOT NULL DEFAULT FALSE,   -- TRUE only after a provider-verified resolution
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Same platform handle (incl. host) can only be attached once per contact.
    CONSTRAINT contact_handle_unique UNIQUE (contact_id, platform, handle, host)
);

CREATE INDEX contact_workspace_idx ON contact (workspace_id);
CREATE INDEX contact_handle_workspace_idx ON contact_handle (workspace_id);
CREATE INDEX contact_handle_contact_idx ON contact_handle (contact_id);
