-- V5: publications, deliveries and delivery attempts (UC-05 first slice,
-- ADR-004, ADR-013, ADR-015). Text-only payloads executed synchronously in the
-- request; durable jobs, leases and worker execution land with UC-07. Dialect
-- kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE publication (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   BIGINT NOT NULL REFERENCES workspace (id),
    post_id        BIGINT NOT NULL REFERENCES post (id),
    revision_id    BIGINT NOT NULL REFERENCES post_revision (id),
    submission_key VARCHAR(128) NOT NULL,              -- workspace-scoped idempotency key (ADR-015)
    state          VARCHAR(24)  NOT NULL DEFAULT 'IN_PROGRESS',  -- aggregate, derived per ADR-015
    payload_hash   VARCHAR(64)  NOT NULL,               -- SHA-256 over all delivery payload hashes
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT publication_submission_key_unique UNIQUE (workspace_id, submission_key)
);

-- One delivery per publication and destination; the payload snapshot is
-- immutable once approved (ADR-015). account_id is workspace-checked in the
-- service layer before insert (ADR-013).
CREATE TABLE delivery (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id        BIGINT NOT NULL REFERENCES workspace (id),
    publication_id      BIGINT NOT NULL REFERENCES publication (id),
    account_id          BIGINT NOT NULL REFERENCES account (id),
    platform            VARCHAR(32)  NOT NULL,
    destination_label   VARCHAR(200) NOT NULL,
    host                VARCHAR(255),
    provider_account_id VARCHAR(255) NOT NULL,
    payload_text        TEXT NOT NULL,                  -- approved, mention-resolved text; immutable
    payload_hash        VARCHAR(64)  NOT NULL,
    state               VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    external_ref        VARCHAR(255),                   -- provider reference, only when verified
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT delivery_per_destination_unique UNIQUE (publication_id, account_id)
);

-- Append-only attempt/stage audit per delivery (ADR-015); detail is redacted
-- and credential-free (ADR-007).
CREATE TABLE delivery_attempt (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    delivery_id  BIGINT NOT NULL REFERENCES delivery (id),
    attempt_no   INTEGER NOT NULL DEFAULT 1,
    stage        VARCHAR(32) NOT NULL DEFAULT 'send',
    outcome      VARCHAR(24) NOT NULL,                 -- SUCCESS | FAILED | UNKNOWN (ADR-015)
    detail       VARCHAR(500),
    external_ref VARCHAR(255),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX publication_workspace_idx ON publication (workspace_id);
CREATE INDEX publication_post_idx ON publication (post_id);
CREATE INDEX delivery_publication_idx ON delivery (publication_id);
CREATE INDEX delivery_attempt_delivery_idx ON delivery_attempt (delivery_id);
