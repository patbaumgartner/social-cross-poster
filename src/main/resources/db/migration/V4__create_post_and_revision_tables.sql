-- V4: workspace-scoped posts (draft containers) with immutable versioned
-- revisions, selected destinations and layered text overrides per UC-04,
-- ADR-003 (points 1-2), ADR-004, ADR-013, ADR-015. Dialect kept compatible
-- with H2 in PostgreSQL mode (tests).
CREATE TABLE post (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id        BIGINT NOT NULL REFERENCES workspace (id),
    title               VARCHAR(200),
    state               VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',  -- DRAFT | READY | ARCHIVED
    current_revision_id BIGINT,                                 -- pointer set after first revision
    version             BIGINT NOT NULL DEFAULT 0,             -- optimistic version, bumped per save
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE post_revision (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    post_id      BIGINT NOT NULL REFERENCES post (id),
    revision_no  INTEGER NOT NULL,                           -- 1-based, immutable once written (ADR-015)
    default_text TEXT NOT NULL DEFAULT '',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT post_revision_post_no_unique UNIQUE (post_id, revision_no)
);

ALTER TABLE post ADD CONSTRAINT post_current_revision_fk
    FOREIGN KEY (current_revision_id) REFERENCES post_revision (id);

-- Destinations selected for one revision. account_id is workspace-checked in
-- the service layer (findByIdAndWorkspaceId) before insert (ADR-013).
CREATE TABLE revision_destination (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    revision_id  BIGINT NOT NULL REFERENCES post_revision (id),
    account_id   BIGINT NOT NULL REFERENCES account (id),
    CONSTRAINT revision_destination_unique UNIQUE (revision_id, account_id)
);

-- Layered text overrides for one revision (ADR-003 point 1). target is
-- 'platform:<platformKey>' or 'destination:<accountId>'. text NULL = absent
-- (inherit from the next layer); empty string = explicit clear, which is then
-- validated (blocking) instead of silently inherited.
CREATE TABLE revision_override (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace (id),
    revision_id  BIGINT NOT NULL REFERENCES post_revision (id),
    target       VARCHAR(64) NOT NULL,
    text         TEXT,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT revision_override_target_unique UNIQUE (revision_id, target)
);

CREATE INDEX post_workspace_idx ON post (workspace_id);
CREATE INDEX post_revision_post_idx ON post_revision (post_id);
CREATE INDEX revision_destination_revision_idx ON revision_destination (revision_id);
CREATE INDEX revision_override_revision_idx ON revision_override (revision_id);
