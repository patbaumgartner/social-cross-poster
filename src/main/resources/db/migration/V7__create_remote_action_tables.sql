-- V7: remote actions — verified edit/delete of a published destination (UC-08
-- first slice, ADR-015). A remote action is a SEPARATE record: it never replaces
-- or rewrites the original delivery or publication (ADR-015: "Edit/delete outcomes
-- are separate remote actions, never replacements for the original delivery
-- result"), and a provider rejection never changes a formerly SUCCESS delivery.
-- Dialect kept compatible with H2 in PostgreSQL mode (tests).
CREATE TABLE remote_action (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  BIGINT NOT NULL REFERENCES workspace (id),
    delivery_id   BIGINT NOT NULL REFERENCES delivery (id),
    action        VARCHAR(8)  NOT NULL,                  -- EDIT | DELETE
    state         VARCHAR(24) NOT NULL DEFAULT 'PENDING',  -- PENDING|RUNNING|SUCCESS|FAILED|UNKNOWN|CANCELED
    payload_text  TEXT,                                   -- replacement text for EDIT (NULL for DELETE); immutable once set
    payload_hash  VARCHAR(64),                            -- SHA-256 of payload_text (NULL for DELETE)
    external_ref  VARCHAR(255),                           -- remote post reference, only when the delivery confirmed it
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Append-only attempts of one remote action (ADR-015); detail is redacted and
-- credential-free (ADR-007).
CREATE TABLE remote_action_attempt (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id     BIGINT NOT NULL REFERENCES workspace (id),
    remote_action_id BIGINT NOT NULL REFERENCES remote_action (id),
    attempt_no       INTEGER NOT NULL DEFAULT 1,
    stage            VARCHAR(32) NOT NULL,               -- 'edit' | 'delete' | 'authorize'
    outcome          VARCHAR(24) NOT NULL,               -- SUCCESS | FAILED | UNKNOWN (ADR-015)
    detail           VARCHAR(500),
    external_ref     VARCHAR(255),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX remote_action_delivery_idx ON remote_action (delivery_id);
CREATE INDEX remote_action_attempt_action_idx ON remote_action_attempt (remote_action_id);
